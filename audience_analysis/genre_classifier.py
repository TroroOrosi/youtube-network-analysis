def classify(title: str) -> str:
    """チャンネル名を 10 ジャンルのいずれか（または未分類）に割り当てる。"""
    if not isinstance(title, str) or not title.strip():
        return UNCLASSIFIED
    t = title.strip()
    if t in CHANNEL_OVERRIDES:
        return CHANNEL_OVERRIDES[t]
    low = t.lower()
    for genre, keywords in GENRE_KEYWORDS.items():
        for kw in keywords:
            if kw.lower() in low:
                return genre
    return UNCLASSIFIED


